#!/usr/bin/env python3
"""Merges the manifests of several vehicles into the single JSON the game reads (`VehicleModels.json`).

    python collect_models.py <folder-with-manifests> --out <game>/src/shared/VehicleModels.json [--force]

Validates every manifest with check_vehicle.py first and refuses to write if any has errors (--force overrides).
The output keeps the manifest schema 2 per vehicle, without the build-time `verify` list.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_vehicle  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folder", help="folder searched recursively for *.manifest.json")
    ap.add_argument("--out", required=True, help="VehicleModels.json to write")
    ap.add_argument("--force", action="store_true", help="write even if a manifest has errors")
    args = ap.parse_args(argv)

    paths = check_vehicle.find_manifests([args.folder])
    if not paths:
        print("ERROR: no *.manifest.json found", file=sys.stderr)
        return 2
    models, failed = {}, False
    for path in paths:
        m = json.loads(path.read_text(encoding="utf-8"))
        errors, _warnings = check_vehicle.check_manifest(m)
        for e in errors:
            print(f"ERROR {m.get('asset', path.name)}: {e}", file=sys.stderr)
        failed = failed or bool(errors)
        m.pop("verify", None)
        models[m["asset"]] = m
    if failed and not args.force:
        print("Not written: fix the errors above (or use --force).", file=sys.stderr)
        return 1
    for w in check_vehicle.collection_warnings(models):
        print(f"WARN collection: {w}")
    doc = {
        "_comment": "Generated by roblox-vehicle-modeler/scripts/collect_models.py. Do not edit by hand. "
                    "Units: studs. Frame: Roblox model (+X right, +Y up, +Z back; nose = -Z; origin = ground under the centre).",
        "schema": 2,
        "models": dict(sorted(models.items())),
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(models)} models)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
