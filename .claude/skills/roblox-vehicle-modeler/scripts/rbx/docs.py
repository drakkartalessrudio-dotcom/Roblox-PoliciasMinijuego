"""Writes `<Asset>_PARTS.md`, the Roblox parts document of a vehicle (pure Python).

Generated from the spec and the manifest; never edit it by hand.
"""
from __future__ import annotations

import datetime
import os


def render(spec: dict, manifest: dict, spec_path: str) -> str:
    asset = manifest["asset"]
    rig = manifest["rig"]
    dims = manifest["dimensions"]
    tris = manifest["tris"]
    lines: list[str] = []
    add = lines.append

    add(f"# {asset} — Roblox vehicle parts document")
    add("")
    add(f"> Generated by the `roblox-vehicle-modeler` skill on {datetime.date.today().isoformat()}. "
        "**Do not edit by hand**: edit the spec and rebuild.")
    add("")
    add("## 1. Summary")
    add("")
    add(spec.get("brief", "(no brief)"))
    add("")
    add(f"- **Spec (source of truth):** `{os.path.abspath(spec_path)}`")
    add(f"- **Class / tier / body type:** {manifest.get('class')} · tier {manifest.get('tier')} · `{manifest.get('bodyType')}`")
    add(f"- **Size (studs):** length {dims.get('length')} · width {dims.get('width')} · height {dims.get('height')} · "
        f"wheelbase {dims.get('wheelbase')} · wheel radius {dims.get('wheel_radius')}")
    budget = tris.get("budget")
    verdict = "" if budget is None else (" ✅ within budget" if tris["total"] <= budget else " ❌ OVER BUDGET")
    add(f"- **Triangles:** {tris['total']} (budget {budget}){verdict}")
    add(f"- **Frame:** {manifest['units']}")
    add("")
    add("## 2. Pieces (one MeshPart each)")
    add("")
    add("| Piece | Roblox material | Colour (RGB) | Transparency | Centre (x, y, z) | Size (x, y, z) | Tris |")
    add("|---|---|---|---|---|---|---|")
    for name, p in manifest["parts"].items():
        add(f"| `{name}` | {p['material']} | {p['color']} | {p['transparency']} | {p['center']} | {p['size']} | {p['tris']} |")
    add("")
    add("## 3. Driving rig data (read by `VehicleBody`)")
    add("")
    add("| Wheel | Hub (x, y, z) | Radius | Width | Steers | Driven |")
    add("|---|---|---|---|---|---|")
    for tag, w in rig.get("wheels", {}).items():
        add(f"| {tag} | {w['hub']} | {w['radius']} | {w['width']} | {w['steer']} | {w['drive']} |")
    add("")
    seat = rig["seat"]
    add(f"- **Driver seat:** position {seat['position']} · size {seat['size']} · {seat['side']}-hand drive · "
        f"source: {seat['source']}. Tune it with `roblox.seat` in the spec after looking at the avatar in Studio.")
    add(f"- **Wheel radius (mean):** {rig.get('wheelRadius')} · track width {rig.get('trackWidth')} · "
        f"wheelbase {rig.get('wheelbase')} · ground clearance {rig.get('groundClearance')}")
    coll = rig.get("collision")
    if coll:
        add(f"- **Collision:** `Chassis` with `CollisionFidelity = {coll['fidelity']}`, box {coll['size']} centred at {coll['center']}")
    if rig.get("massKg"):
        add(f"- **Mass hint:** {rig['massKg']} kg (the game decides the real mass through its handling profile)")
    add("")
    add("## 4. Sockets (Attachments inside `Chassis`, Roblox frame)")
    add("")
    add("| Socket | Position (x, y, z) |")
    add("|---|---|")
    for name, pos in manifest["sockets"].items():
        add(f"| `{name}` | {pos} |")
    add("")
    add("## 5. Decisions")
    add("")
    for d in spec.get("decisions", []):
        add(f"- {d}")
    add("")
    problems = manifest.get("verify") or []
    add("## 6. Export check")
    add("")
    if problems:
        add("The FBX does **not** match the manifest:")
        for p in problems:
            add(f"- ❌ {p}")
    else:
        add("The FBX was re-read after writing: every piece has identity rotation/scale and the same centre and size "
            "as the manifest turned 180 degrees about Y (Studio's importer undoes that turn; tolerance 0.02 studs).")
    add("")
    add("## 7. Import into Roblox Studio")
    add("")
    add(f"1. Avatar → Import 3D → `Export/{manifest['fbx']}` (keep the default scale; `VehicleAssembler` sets each "
        "piece's size and position from the manifest, so an importer scale difference is corrected).")
    add(f"2. Rename the imported Model `{asset}`, right-click → *Save to File* → `src/shared/VehicleMeshes/{asset}.rbxm`.")
    add("3. Run `VehicleBody.verify(model)` from the command bar (see `references/studio-import.md`) and read the report.")
    add("")
    add("## 8. How to modify")
    add("")
    add("1. Shape or colour: edit the spec (`parts`, `roblox.materials`) → rebuild with `build_vehicle.py`.")
    add("2. Never edit the FBX or the manifest by hand; both are regenerated.")
    add("3. Keep piece names stable (`Chassis`, `Tire_FL`, …): the Luau side finds them by name.")
    add("")
    return "\n".join(lines)


def write(spec: dict, manifest: dict, spec_path: str, out_dir: str) -> str:
    path = os.path.join(out_dir, f"{manifest['asset']}_PARTS.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(render(spec, manifest, spec_path))
    return path
